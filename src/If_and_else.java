public class If_and_else {
    public static void main(String[] args) {
        /* this is for the java conditionals statments
        if
        if elese
        if , else if and else
        switch case
         */
        int x =99;
        if (x>10)
        {
            System.out.println("statment of the if condition is verified");
        } else if (x==10) {
            System.out.println("statment of the else if condition is verified");
        } else if (x<10 & x>=8) {
            System.out.println("statment of the else if condition is verified between 8 to 10");
        }
        else
        {
            System.out.println("all statments are not verified so else condition is verified");
        }


    }
}
